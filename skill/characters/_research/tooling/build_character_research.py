def render_track(card, track_index, key, title):
    sources = card["sources"][key]
    lines = [
        f"# {card['name']}：{title}",
        "",
        "## Collection Metadata",
        f"- Dimension: {title}",
        "- Collection strategy: local-first / fictional-character adaptation",
        f"- Sources searched: {len(sources)} 个独立场景锚点",
        f"- Sources used: {len(sources)}",
        f"- Primary vs secondary ratio: {len(sources)}:0",
        "- URL floor: N/A；最高权重来源为用户提供的本地小说分卷，不伪造网页 URL。",
        "",
    ]
    for item in sources:
        lines.extend([
            "## Source Metadata",
            "- URL: N/A (local primary text)",
            f"- Local source: {CORPUS / item['path']}",
            f"- Scene anchor: {item['scene']}",
            "- Source type: novel scene",
            "- Grounding level: primary source / 一手正文",
            "- Access note: user-provided local corpus",
            "- Source weight: 1",
            "- Date: edition-dependent / not normalized",
            "",
        ])
    lines.append("## Evidence")
    lines.extend(f"- {item}" for item in card["tracks"][key])
    lines.extend([
        "",
        "## Patterns and Repeated Themes",
        f"- {card['tracks'][key][-1]}",
        "",
        "## Contradictions",
        f"- {card['contradictions'][track_index % len(card['contradictions'])]}",
        "",
        "## Inferences (clearly marked)",
        f"- 推断：{card['inferences'][track_index % len(card['inferences'])]}",
        "",
        "## Gaps and Missing Information",
        f"- {card['gaps'][track_index]}",
    ])
    if card["identity_boundary"]:
        lines.extend(["", "## Identity Boundary", f"- {card['identity_boundary']}"])
    return "\n".join(lines) + "\n"


